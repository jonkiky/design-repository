const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const crypto=require('node:crypto');
const {build}=require('../../chatbot-system-poc-1106/frontend/node_modules/esbuild');
const root=path.resolve(__dirname,'..');
async function main(){
  const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'caiyan-design-check-'));
  const store=new Map();
  global.location={search:'',protocol:'http:'};global.localStorage={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v)};
  await build({entryPoints:[path.join(root,'src/demo.ts')],bundle:true,platform:'node',format:'cjs',outfile:path.join(tmp,'demo.cjs'),logLevel:'silent'});
  const {demoApi:api,demoInternals:internals}=require(path.join(tmp,'demo.cjs'));
  let checks=0;const ok=(x,msg)=>{assert.ok(x,msg);checks++;};
  const initial=await api('/cases');ok(initial.length===4,'four fixture cases');
  const facets=await api('/search/facets','POST',{});ok(facets.fields.length===18,'all 18 searchable fields retained');
  const res=await api('/search','POST',{query:'合同',filters:{province:['浙江省','江苏省'],cause:['商品房预售合同纠纷']}});
  ok(res.items.length===2,'OR within a field / AND across fields');
  ok((await api('/search','POST',{query:'完全不存在的案情字串'})).items.length===0,'no silent fallback for zero matches');
  ok((await api('/search','POST',{date_from:'2025-06-20',date_to:'2025-06-23'})).items.length===2,'inclusive date range');
  const c=await api('/cases','POST',{title:'交互验收测试案件',claims:'合同资料核对',position:'原告代理律师',research_date:'2026-11-10'});
  ok((await api('/cases/'+c.id)).title==='交互验收测试案件','create and read');
  await api('/cases/'+c.id,'PATCH',{title:'已编辑测试案件'},{'If-Match':'1'});
  await assert.rejects(api('/cases/'+c.id,'PATCH',{title:'不应覆盖'},{'If-Match':'1'}));checks++;
  const mat=await api('/cases/'+c.id+'/materials/text','POST',{name:'测试材料.txt',text:'原文应保持不变。',kind:'律师整理记录'});
  ok((await api('/materials/'+mat.id)).text==='原文应保持不变。','text material persisted');
  let similar=await api('/cases/'+c.id+'/similar-cases');
  similar=await api('/cases/'+c.id+'/similar-cases/analyze','POST',{version:similar.version,options:{...similar.options,query:'合同'}});
  ok(similar.count>0&&!similar.needs_analysis,'similar case analysis');
  const first=similar.response.items[0].document_id;
  similar=await api('/cases/'+c.id+'/similar-cases/'+first+'/relevance','PUT',{version:similar.version,relevant:false});
  ok(similar.excluded_items.length===1&&!similar.response.items.some(i=>i.document_id===first),'exclude case');
  similar=await api('/cases/'+c.id+'/similar-cases/analyze','POST',{version:similar.version,options:similar.options});
  ok(!similar.response.items.some(i=>i.document_id===first),'exclusion persists after reanalysis');
  similar=await api('/cases/'+c.id+'/similar-cases/'+first+'/relevance','PUT',{version:similar.version,relevant:true});
  ok(similar.response.items.some(i=>i.document_id===first),'restore excluded case');
  const oldNow=Date.now;
  const waiting=(await api('/cases/demo-housing')).runs.find(r=>r.status==='waiting_input');
  ok(waiting.wait_payload.kind==='workflow','waiting task uses the UI workflow contract');
  await api('/runs/'+waiting.id+'/resume','POST',{answer:{workflow:'evidence.gaps'}});
  Date.now=()=>oldNow()+2000;await api('/cases/demo-housing');Date.now=oldNow;
  ok((await api('/runs/'+waiting.id)).status==='succeeded'&&(await api('/runs/'+waiting.id)).plan[0]==='evidence.gaps','resume creates the selected result');
  async function finish(workflow,extra={}){const r=await api('/cases/'+c.id+'/requests','POST',{goal:'测试研究内容',workflow,...extra});Date.now=()=>oldNow()+2000;await api('/cases/'+c.id);Date.now=oldNow;return r;}
  for(const workflow of ['case.timeline','evidence.gaps','case.assess','document.generate'])await finish(workflow);
  let detail=await api('/cases/'+c.id);ok(['timeline','evidence','research','document'].every(k=>detail.artifacts.some(a=>a.kind===k)),'four workflow results');
  const timeline=detail.artifacts.find(a=>a.kind==='timeline');
  const next=await api('/artifacts/'+timeline.id+'/versions','POST',{content_hash:timeline.content_hash,facts:timeline.structured.facts.map(f=>({...f,description:'人工修订事件'}))});
  ok(next.version===2&&next.review_status==='pending','timeline version and review reset');
  ok((await api('/materials/'+mat.id)).text==='原文应保持不变。','editing does not overwrite source');
  const research=detail.artifacts.find(a=>a.kind==='research');await finish('research.followup',{research_artifact_id:research.id});
  detail=await api('/cases/'+c.id);ok(detail.artifacts.find(a=>a.kind==='research').structured.conversation.length===1,'research follow-up retained');
  const evidence=detail.artifacts.find(a=>a.kind==='evidence');await finish('evidence.followup',{evidence_artifact_id:evidence.id});
  ok((await api('/cases/'+c.id)).artifacts.some(a=>a.kind==='evidence_answer'),'evidence follow-up retained');
  const doc=detail.artifacts.find(a=>a.kind==='document');
  const newDoc=await api('/artifacts/'+doc.id+'/versions','POST',{content_hash:doc.content_hash,body:'# 已编辑文书\n测试正文'});
  await api('/artifacts/'+newDoc.id+'/reviews','POST',{content_hash:newDoc.content_hash,confirmed:true});
  ok((await api('/artifacts/'+newDoc.id)).review_status==='reviewed','document review');
  const archive=await api('/artifacts/'+newDoc.id+'/reference-documents','POST',{content_hash:newDoc.content_hash});
  ok(archive.available&&archive.name.endsWith('.docx'),'Word archive');
  const bytes=Buffer.from(await internals.wordBlob('中文文书\n第二段').arrayBuffer());fs.writeFileSync(path.join(tmp,'sample.docx'),bytes);
  ok(bytes.readUInt32LE(0)===0x04034b50,'OOXML ZIP signature');
  const configs=await api('/admin/configurations');const test=await api('/admin/configurations/tests','POST',configs[0].content);
  const published=await api('/admin/configurations/publish','POST',{test_id:test.id,content:configs[0].content,reviewed:true,base_version:1});ok(published.version===2,'configuration history');
  await api('/materials/'+mat.id,'DELETE');detail=await api('/cases/'+c.id);
  ok(detail.materials.length===0&&detail.similar_cases.needs_analysis,'withdrawal marks dependent research stale');
  await assert.rejects(api('/artifacts/'+newDoc.id+'/reference-documents','POST',{}));checks++;
  await api('/cases/'+c.id,'DELETE',undefined,{'If-Match':String(detail.revision)});await assert.rejects(api('/cases/'+c.id));checks++;
  await api('/auth/logout','POST');ok(await api('/me')===null,'logout');await api('/auth/login','POST',{});ok((await api('/me')).id==='design-user','demo login');
  for(const [file,hash] of Object.entries(JSON.parse(fs.readFileSync(path.join(root,'source-baseline.json'))))){assert.equal(crypto.createHash('sha256').update(fs.readFileSync(path.resolve(root,'..',file))).digest('hex'),hash,'Original file changed: '+file);}
  ok(true,'original frontend files unchanged');
  console.log(JSON.stringify({passed:checks,wordFixture:path.join(tmp,'sample.docx'),originalSource:'unchanged'},null,2));
}
main().catch(e=>{console.error(e);process.exit(1)});
